import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const TEMPLATES_DIR = path.join(ROOT_DIR, "packages", "templates", "templates");
const OUTPUT_FILE = path.join(
  ROOT_DIR,
  "packages",
  "templates",
  "src",
  "GeneratedTemplateCatalog.ts",
);

const entries = fs
  .readdirSync(TEMPLATES_DIR, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const catalogItems = [];

for (const dirName of entries) {
  const baseDir = path.join(TEMPLATES_DIR, dirName);
  const manifestPath = path.join(baseDir, "template.json");
  const liquidPath = path.join(baseDir, "template.liquid");
  const stylesPath = path.join(baseDir, "styles.css");
  const samplePath = path.join(baseDir, "samples", "default.json");

  if (!fs.existsSync(manifestPath)) continue;

  const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
  const liquidTemplate = fs.readFileSync(liquidPath, "utf8");
  const stylesCss = fs.existsSync(stylesPath) ? fs.readFileSync(stylesPath, "utf8") : "";
  const defaultSample = fs.existsSync(samplePath)
    ? JSON.parse(fs.readFileSync(samplePath, "utf8"))
    : {};

  catalogItems.push({
    id: manifest.id,
    manifest,
    liquidTemplate,
    stylesCss,
    defaultSample,
  });
}

const source = `// AUTO-GENERATED BY scripts/GenerateTemplateCatalog.mjs — DO NOT EDIT BY HAND
import type { TemplateManifest } from "@tinytldr/core";

export interface EmbeddedTemplateCatalogEntry {
  readonly id: string;
  readonly manifest: TemplateManifest;
  readonly liquidTemplate: string;
  readonly stylesCss: string;
  readonly defaultSample: Record<string, unknown>;
}

export const GENERATED_TEMPLATE_CATALOG: readonly EmbeddedTemplateCatalogEntry[] = ${JSON.stringify(
  catalogItems,
  null,
  2,
)} as unknown as readonly EmbeddedTemplateCatalogEntry[];
`;

fs.writeFileSync(OUTPUT_FILE, source, "utf8");
console.log(`Generated ${OUTPUT_FILE} with ${catalogItems.length} templates.`);
